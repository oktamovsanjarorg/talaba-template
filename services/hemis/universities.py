def search_universities(query: str, limit: int = 6) -> list:
    q = query.strip().lower()
    if not q:
        return UNIVERSITIES[:limit]
    
    exact_matches = []
    partial_matches = []
    
    for u in UNIVERSITIES:
        if q == u["short"].lower() or q == u["domain"].lower():
            exact_matches.append(u)
        elif q in u["name"].lower() or q in u["short"].lower() or q in u["domain"].lower() or q in u.get("region", "").lower():
            partial_matches.append(u)
            
    combined = exact_matches + partial_matches
    # Takrorlanmas qilib olish
    seen = set()
    result = []
    for item in combined:
        if item["domain"] not in seen:
            seen.add(item["domain"])
            result.append(item)
    return result[:limit]

def get_paginated_universities(page: int = 1, page_size: int = 6):
    total = len(UNIVERSITIES)
    start = (page - 1) * page_size
    end = start + page_size
    items = UNIVERSITIES[start:end]
    total_pages = (total + page_size - 1) // page_size
    return items, page, total_pages
